def generate_and_save_dataset():
    """Builds, validates, and writes products.csv to DATA_DIR."""
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    products = build_catalog_data()
    df = pd.DataFrame(products)

    # Validate essential columns
    required_cols = [
        "product_id", "title", "brand", "category", "subcategory",
        "price", "original_price", "rating", "review_count",
        "ram", "storage", "processor", "gpu", "display",
        "battery_life", "os", "weight", "use_cases", "features",
        "description", "image_url"
    ]
    for col in required_cols:
        if col not in df.columns:
            raise ValueError(f"Missing required column: {col}")

    # Ensure numeric types
    df["price"] = pd.to_numeric(df["price"], errors="coerce").fillna(0).astype(int)
    df["original_price"] = pd.to_numeric(df["original_price"], errors="coerce").fillna(0).astype(int)
    df["rating"] = pd.to_numeric(df["rating"], errors="coerce").fillna(0.0).astype(float)
    df["review_count"] = pd.to_numeric(df["review_count"], errors="coerce").fillna(0).astype(int)

    # Save to CSV
    df.to_csv(PRODUCTS_CSV_PATH, index=False)
    print(f"Successfully generated {len(df)} products -> {PRODUCTS_CSV_PATH}")

    # Save summary metadata
    metadata = {
        "total_products": len(df),
        "categories": df["category"].value_counts().to_dict(),
        "price_min": int(df["price"].min()),
        "price_max": int(df["price"].max()),
        "price_median": int(df["price"].median()),
        "average_rating": float(round(df["rating"].mean(), 2)),
    }
    with open(DATASET_METADATA_PATH, "w") as f:
        json.dump(metadata, f, indent=2)
    print(f"Saved dataset metadata -> {DATASET_METADATA_PATH}")

    return df


if __name__ == "__main__":
    generate_and_save_dataset()
